/**
 * 图层数值合法性守卫 —— 拦住「非有限数」这一格静默失败。
 *
 * ════════════════════════════════════════════════════════════════════════════
 * 为什么这条守卫必须存在（不是防御性编程洁癖）
 * ════════════════════════════════════════════════════════════════════════════
 * `layer.ts` 写的是「`opacity` 超出范围由 normalize 夹紧，渲染侧不再判」。
 * 那句话说的是**范围**（0.5 vs 2），不是**合法性**（NaN / Infinity 根本不是数）。
 * 两者混在一起时，渲染侧会漏掉后者，而漏掉的后果全部是静默的：
 *   ① `ctx.globalAlpha = NaN` 是**非法值**，浏览器**静默忽略这次赋值**
 *      ⇒ 该层按外层 alpha 画，屏幕上看起来"稍微透了一点"，没人会怀疑是 NaN；
 *   ② `ctx.translate(NaN, y)` 会让整条变换矩阵变成 NaN ⇒ 该层一个像素都不落，
 *      而且**不抛错、不报警**。表现是"导出的图里少了一个图层，但导出成功了"。
 * 第二格正是本仓反复踩的形态：**静默变空**。
 *
 * ════════════════════════════════════════════════════════════════════════════
 * 为什么"发现非法值 ⇒ 不画 + 诊断"，而不是"当 0 用掉"
 * ════════════════════════════════════════════════════════════════════════════
 * 当成 0 画出去，这个图层会跑到画布左上角，导出图看着"少了一块但好像也说得过去"
 * —— 人会以为这是设计问题，于是不去查存档。而不画 + 一条诊断，调用方拿到
 * 非空诊断数组就知道"这一层有问题"，能定位到具体字段和原值。
 * **把错误吞掉换成"看起来还行"是本仓明令禁止的失败模式。**
 *
 * 为什么 `z` 也在这张表里：`z` 不参与绘制，但它参与**排序**。`NaN` 混进
 * `Array.prototype.sort` 的比较器会让排序结果依赖引擎实现（规范只说比较器
 * 返回 NaN 时"当作 0"，实测不同引擎给出不同顺序）⇒ 同一份文档的图层叠放
 * 顺序会飘。所以 `z` 非有限数同样按"不画 + 诊断"处理，并在排序里先按
 * 「是否有限」分档（见 `render.ts` 的 `zRankOf`），保证比较器里永远不出现 NaN。
 */

import type { LayerBase } from '../model/layer';

/**
 * 参与守卫的字段。
 *
 * 为什么是**显式清单**而不是 `Object.keys(layer)` 遍历：后者会连
 * `id` / `name` / `type` 这些非数值字段一起进来（要额外判断类型），
 * 而且将来给 `LayerBase` 加一个新的几何字段时，**遍历版会静默漏掉它**，
 * 清单版则提醒作者"这里要不要补"。清单短、可读、可被测试逐项点名。
 */
export type GuardedField = 'x' | 'y' | 'w' | 'h' | 'opacity' | 'rotation' | 'z';

/** 命中的第一个非法字段（只报第一个：报一串字段名对定位没有额外帮助）。 */
export interface NonFiniteField {
  readonly field: GuardedField;
  readonly value: number;
}

/** 守卫清单。顺序 = 检查顺序 = 报告顺序，所以顺序本身是契约的一部分。 */
const GUARDED_FIELDS: readonly GuardedField[] = [
  'x',
  'y',
  'w',
  'h',
  'opacity',
  'rotation',
  'z',
];

/**
 * 找出第一个非有限数字段。
 *
 * 只判 `Number.isFinite`，**不判范围**（范围是 `normalize` 的职责）：
 * `opacity: 2` 是"超出范围"，由 normalize 夹到 1，渲染侧照常画；
 * `opacity: NaN` 是"根本不是数"，渲染侧必须拦。这条分工是 `layer.ts`
 * 那句注释的真实含义。
 *
 * ── 为什么也不判 `w/h <= 0`（原理由**撤回三次**，完整留档）──────────────
 * **第 1 版（错）**：「负宽高在 canvas 上是镜像绘制，语义明确、不是错误」。
 *   错因（2026-11-02 随 `flipX/flipY` 落地**订正过一次**，原写"本模型没有
 *   `flipX/flipY` 字段，镜像无处表达"——那句现在不成立了）：
 *   **镜像现在有专门字段，负宽高就不该再兼职表达镜像。** `fillRect(x, y, -50, h)`
 *   镜像的是 `x` 与 `x+w` 之间的区间（盒子位置跟着变），而 `flipX` 绕图层中心
 *   镜像（中心不动）—— 两者语义不同，混用会让同一个视觉结果有两种数据表达，
 *   存取、命中测试、缩放手柄全都要各判一次。所以模型层只认 `flipX/flipY`，
 *   负宽高在本仓的定义始终是"尺寸退化了"，图元各自抛错（见下面第 ③ 条）。
 * **第 2 版（也错）**：「`normalizeLayer` 夹到 >= 8 ⇒ **负值到不了渲染层**」。
 *   与下面第 ③ 节同一个错：`render.ts` **不做 normalize**。实测（裸 doc 直接喂
 *   `renderDoc`，`w=-50` 的矩形）⇒ 守卫返回 `null`（放行）、文档产出
 *   `[{layerType:'shape', reason:'draw-threw'}]` ⇒ **负值确实到达了渲染层**，
 *   只是被图元自己拦下了。用它当理由会让人以为"渲染侧永远见不到负值"。
 * **现行理由（都不依赖可达性，因此不会再过期）**：
 *   · **`line` 的 `w=0` 是一条合法竖线**（`h=0` 同理是横线）：线是被"压扁的盒子"，
 *     单独判 `w<=0` 会杀掉所有竖线。只有 `w<=0 && h<=0` 才是真失败。
 *   · **`polygon` 不吃 `w/h`**：顶点是绝对坐标，路径只由 `points` 决定；而引擎的
 *     `translate(x+w/2,y+h/2) → rotate → translate(-w/2,-h/2)` 在 `w=h=0` 时前后
 *     抵消、原点落在 `(x,y)`，几何位置是对的。按 `w/h` 判会误杀它。
 *   · `rect` / `ellipse` / `image` 的 `w<=0` 确实画不出东西，但它们各自会抛
 *     （`ShapeDrawError` / `ImageDrawError`）⇒ `render.ts` 转成 `draw-threw` 诊断
 *     （上面那条实测就是活证据）。**在那里拦比在这里拦更可归因**：图元的错误消息
 *     带图层 id 与实际尺寸（"矩形宽高必须是有限正数，收到 0×50"），而这里的 reason
 *     只能写成 `non-finite-field` —— 这对 `w=0` 是**名不副实**（0 是有限数）。
 *
 * ★ 教训（写进正文，因为它决定了理由怎么写）：**别把"数据可达性"当理由。**
 *   可达性随调用方是否 normalize 而变，会在别人改一行之后失效，而注释**不会跟着报错**
 *   （注释不参与断言 ⇒ 失效是静默的）。语义与归因质量不随外部条件变化 ⇒ 优先用它们。
 *   我连续三次踩这一格（本文件两次、测试一次），见 `unit-poster-canvas.mjs` 的 RC9。
 * 一句话：**这里管"是不是数"，图元管"数能不能画"**。两层分开，诊断里读者
 * 才能一眼分清"数据坏"与"尺寸退化"。**本守卫不许**去拦 `w/h<=0`。
 *
 * ── ★ 附：`w=0` / 细线的可达性（三条，缺一句都会误导）────────────────────
 * 上面「`line` 的 `w=0` 是合法竖线」说的是**图元的能力**，不是"数据现在能不能到"。
 *   ① **不经过 normalize 的 doc**：`w=0` / `w=2` 的细线**可以**一路画出来。
 *      实测（裸 doc 直接喂 `renderDoc`）：`w=0 h=200` ⇒ `lineWidth = 1`、诊断 0 条；
 *      `w=2 h=200` ⇒ `lineWidth = 2`、诊断 0 条。这条路径真实存在 —— 模板对象是
 *      手搓的 JS、AI 直出的 doc 也不保证过 normalize。
 *   ② **经过 `normalizeLayer` 的 doc**：`w/h` 被垫到 `>= MIN_LAYER_EDGE (8)`，
 *      细线能力关闭（`0×200` / `2×200` → `8×200` ⇒ 粗细 8）。
 *   ③ 因此"细线能不能画"取决于**调用方有没有先 normalize**，不是渲染层能决定的。
 *      eng-poster-geometry 的 `line.ts` 头注释有可达性矩阵，两处结论一致。
 *
 * 为什么上面①②的变化**不影响**本守卫该不该判 `w/h<=0`：
 *   若哪天 `MIN_LAYER_EDGE` 对 line 开了例外，`w=0` 会名正言顺流到这里；届时判 `w<=0`
 *   ⇒ 所有竖线一次性消失。而**今天**不 normalize 的路径已经能把 `w=0` 送到这里
 *   ⇒ 现在判就等于立刻杀掉那些细线。两种情况下禁令都成立。
 *   **这就是"理由不能用可达性"的实际好处：结论不依赖规格裁决就能做对。**
 *
 * @param layer 任意图层（三大类都继承 `LayerBase`）
 * @returns 命中的字段与值；全部合法返回 `null`
 */
export function findNonFiniteField(layer: LayerBase): NonFiniteField | null {
  for (const field of GUARDED_FIELDS) {
    const value = layer[field];
    if (!Number.isFinite(value)) {
      return { field, value };
    }
  }
  return null;
}

/**
 * 把命中结果写成一行诊断文本。
 *
 * 带上**原值**（`String(NaN)` = `'NaN'`，`Infinity` / `-Infinity` 同理）：
 * "opacity 不合法"和"opacity=NaN"对排查是两件事 —— 后者能让人立刻想到
 * JSON 里的 `null` 被算成了 NaN，前者只能让人去翻存档。
 */
export function describeNonFiniteField(hit: NonFiniteField): string {
  return `字段 ${hit.field} 是 ${String(hit.value)}（必须是有限数）`;
}
