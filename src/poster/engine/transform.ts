/**
 * 图层几何变换 —— `ctx` 上那四个调用，以及为什么必须是这个顺序。
 *
 * ════════════════════════════════════════════════════════════════════════════
 * 为什么单独成一个文件
 * ════════════════════════════════════════════════════════════════════════════
 * 这段逻辑和 `render.ts` 的其余部分关心的事情完全不同：
 *   · `render.ts` 关心**调度**：排序、跳过 hidden、数值守卫、查表、把异常变成诊断；
 *   · 本文件关心**几何**：一个图层该被放到哪儿、怎么转、怎么翻。
 * 两者的失效方式也不同：调度错了表现为"某层没画 / 顺序不对"，
 * 几何错了表现为"画出来了但位置或朝向不对"，而后者**不会产出任何诊断**
 * （坐标系算错不会抛异常）。分开之后，本文件的每条不变量都能被单独指名测试
 * （`unit-poster-flip.mjs` 的 T1/T3/T4 全部只针对本文件）。
 *
 * ════════════════════════════════════════════════════════════════════════════
 * 顺序为什么必须是 translate(中心) → rotate → scale → translate(-w/2,-h/2)
 * ════════════════════════════════════════════════════════════════════════════
 * `ctx.rotate()` 绕的是**当前坐标原点**，不是图层中心。而图元的绘制代码是按
 * 「原点 = 图层左上角」写的（见 `registry.ts` 的约定）。所以：
 *   · 先把原点搬到图层中心（`x+w/2, y+h/2`）
 *   · 再转 —— 此刻原点就是中心，转到哪儿都对
 *   · 再翻转 —— 此刻原点仍是中心，`scale` 绕中心镜像，图层原地翻
 *   · 再把原点搬回"左上角"（相对新原点偏移 `-w/2,-h/2`）
 * 顺序一旦反了（先 rotate 再 translate），被旋转的是**平移向量本身**：
 * 图层不但自转，还会绕画布左上角甩出去一段距离 —— 症状是"图层位置整体偏移，
 * 而且偏移量随角度变化"。
 *
 * ════════════════════════════════════════════════════════════════════════════
 * 翻转为什么能"原地翻"（验算，不是断言）
 * ════════════════════════════════════════════════════════════════════════════
 * 四个调用合成出的变换是：`p ↦ C + R·S·(p − (w/2, h/2))`，其中
 * `C = (x+w/2, y+h/2)` 是图层中心，`R` 是旋转矩阵，`S = diag(±1, ±1)`。
 * 取图层中心自己 `p = (w/2, h/2)`：`p − (w/2,h/2) = 0` ⇒ 结果恒为 `C`，
 * **与 `S` 取什么无关** ⇒ 翻转不移动图层。这就是 `scale` 必须夹在
 * 「原点已在中心」和「原点搬回左上角」之间的全部理由。
 * 若把 `scale` 挪到第一次 `translate` 之前，`S` 会作用在 `C` 这个平移量上
 * （`−1` 时 `C` 变成 `−C`），图层直接镜像到画布另一侧。
 *
 * ★ 这条验算不是文档，是判据：`scripts/smoke/unit-poster-flip.mjs` 用一个
 *   真正的 2D 仿射矩阵栈把中心点代进真跑出来的调用序列里核对（T1），
 *   并有反控 T1-RC-b/c 证明"scale 放错位置"时同一套矩阵算出的中心会跑掉。
 */

import type { LayerBase } from '../model/layer';

/**
 * 把一个图层的几何变换压到 `ctx` 上。
 *
 * ★ **调用方负责 `save()` / `restore()` 配对。** 本函数只管压变换，不管回滚 ——
 *   因为回滚必须发生在 `finally` 里（图元画崩时也要回滚），而那个 `try` 在调用方。
 *   把 save 也塞进来会诱使调用方"画完再 restore"，一旦 `draw` 抛异常就失配。
 *
 * ★ 这里**不做任何数值判断**。`x/y/w/h/rotation` 是 NaN 的情况由
 *   `layerGuard.ts` 在更前面拦下（`render.ts` 用 `findNonFiniteField`），
 *   `flipX/flipY` 是布尔、NaN 进不来（`layers/normalize.ts` 只认 `=== true`）。
 *   在这里再判一次会造成"两个地方都能兜底，所以哪边都没改对"的假象。
 *
 * @param ctx 已经 `save()` 过的 2D 上下文
 * @param layer 任意图层（三大类都继承 `LayerBase`）
 */
export function applyLayerTransform(ctx: CanvasRenderingContext2D, layer: LayerBase): void {
  // ① 原点搬到图层中心
  ctx.translate(layer.x + layer.w / 2, layer.y + layer.h / 2);
  // ② 绕中心旋转（模型存的是度，`ctx.rotate` 吃弧度，只在这一行换算）
  ctx.rotate((layer.rotation * Math.PI) / 180);
  // ③ 翻转。位置与顺序的两个理由见文件头。
  //    写成 `? -1 : 1` 而不是 `Number(flipX) * -1` 之类，是为了让"只可能是 ±1"
  //    在字面上就成立。
  ctx.scale(layer.flipX ? -1 : 1, layer.flipY ? -1 : 1);
  // ④ 原点搬回左上角（相对中心偏移）
  ctx.translate(-layer.w / 2, -layer.h / 2);
}
