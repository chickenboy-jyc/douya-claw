/**
 * 字体族名字段的窄化 —— `unknown` ⇒ 合法的 `fontFamily` 字符串。
 *
 * ════════════════════════════════════════════════════════════════════════════
 * 为什么单独一个文件（而不是放进 `sanitize.ts`）
 * ════════════════════════════════════════════════════════════════════════════
 * `sanitize.ts` 现在正好 **12 个 `export`**，已经顶到门禁上限
 * （`unit-ts-strict.mjs`：单文件 ≤ 12 导出 / ≤ 250 行）。再往里加一个函数就判红，
 * 而把 `sanitize.ts` 里已有的某个导出挪出来，只会制造一次与本次需求无关的跨文件改动
 * （每个调用点都要跟着改 import，评审时看不到"这次到底改了什么"）。
 * ⇒ 在当前结构下，"新开一个文件"是唯一无损的走法。
 *
 * 配套动作：`sanitize.ts` 头部那句"逐字段的窄化规则全在 sanitize.ts"已经同步订正为
 * "在 `sanitize.ts`，字体族名在 `font-family.ts`"。**那句注释不改就会变成假话** ——
 * 而"注释与代码不一致"在本仓是独立的失效形态：下一个人会照着假话去 `sanitize.ts` 里找。
 *
 * ════════════════════════════════════════════════════════════════════════════
 * 为什么是**黑名单**而不是白名单
 * ════════════════════════════════════════════════════════════════════════════
 * 字体名里合法符号太多了：`-apple-system`（前导连字符）、`Helvetica Neue`（空格）、
 * `Source Han Sans SC Heavy`（多段空格）、`思源黑体` / `思源黑体 CN`（中文与空格）、
 * `Noto Sans CJK SC` 等。白名单一定会误伤其中一类，而误伤的后果是"用户填了正确字体名
 * 却被静默清空"——比拒绝更让人困惑（画面看不出问题，只有字宽不对）。
 *
 * 黑名单只禁两类字符，而这两类恰好就是"能让 `ctx.font` 变成另一个意思"的全部：
 *   · 引号 ⇒ 无法**闭合**我们拼出来的 `"family"` ⇒ 无法把后面的默认栈整串吞成字体名的一部分；
 *   · 逗号 ⇒ 无法**插入**额外一项栈 ⇒ 无法绕过默认栈兜底。
 * 只要这两类进不来，引号内的其余字符对 CSS `font` 简写都是无害的字面量。
 */

/**
 * 字体族名长度上限。
 *
 * 真实族名最长约 30 字符（`Source Han Sans SC Heavy` 是 23 个字符，加上 ` Bold` 之类
 * 的后缀也还在 30 上下），64 已经有 2 倍余量。超过 64 基本都是注入或整段文本被误填进来，
 * 而这两种都不该进 `ctx.font`：一段 2KB 的字符串塞进 `font` 里，症状是整层静默用默认字体。
 */
const MAX_FAMILY_LENGTH = 64;

/**
 * 被禁字符表。**每一个都写清理由**（这是本仓的硬性注释标准）。
 *
 * `"` 与 `'` —— 会闭合我们拼出来的 `"<fontFamily>"` 引号。后果不是"字体名不对劲"，
 *   而是**整串默认栈变成字体名的一部分**：`"Ev"il", "PingFang SC", ...` 里，引号一闭合，
 *   后面的 `, "PingFang SC", ...` 会被 `ctx.font` 当成**下一层栈**，语法虽仍合法、
 *   语义却完全变了；更糟的写法会让 `font` 整体解析失败，而 canvas 对无效的 `font`
 *   **不报错**，它**静默沿用到上一层图层遗留的字体** ⇒ 整层字体错乱且没有任何信号。
 *
 * `,` —— 逗号本身就是字体栈的分隔符。字体名里带一个逗号，等于用户悄悄往栈里
 *   **注入额外一层字体**，绕过了"用户字体优先、其余走默认栈"这个兜底约定。
 *
 * `;` 与 `\` —— 在 CSS `font` 简写语法里都没有语义（`\` 在 CSS 里是转义符）。
 *   合法字体名不会包含它们，出现基本就是错误输入（或有人试图用转义绕过引号检查）。
 *
 * `\r` / `\n` —— 同上，且它们会让 `font` 字符串**跨行**：跨行之后，
 *   报错信息里的"哪个图层的字体"这条线索会断（行号/上下文全乱）。
 */
const FORBIDDEN_CHARS: readonly string[] = ['"', "'", ',', ';', '\\', '\r', '\n'];

/**
 * 字体族名窄化。**任何非法输入一律回落到空串**（= 用引擎默认栈），不抛错。
 *
 * 为什么非法值回落到空串而不是抛：`normalizeLayer` 的契约是"**吃任何垃圾都不抛**"
 * （磁盘手改的存档、AI 直出的 JSON、IPC 回包都从这里过）。一个坏字体名不该让
 * 整份海报读不出来 —— 少一个字体远好于"打开就是白屏"。
 * 反过来说，**不能保留原值再让 canvas 去判断**：canvas 不判断，它只会静默沿用旧字体。
 *
 * @param raw 任意输入（磁盘 JSON / AI 输出 / IPC 返回值）
 * @returns 合法的字体族名；空串表示"用引擎默认栈"
 */
export function fontFamilyOf(raw: unknown): string {
  if (typeof raw !== 'string') return '';
  const name = raw.trim();
  if (name === '' || name.length > MAX_FAMILY_LENGTH) return '';
  for (const ch of FORBIDDEN_CHARS) {
    if (name.includes(ch)) return '';
  }
  return name;
}
