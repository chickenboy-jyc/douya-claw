export function getTemplate(key) {
  if (!key) return undefined;
  return ACTIVITY_TEMPLATES.find((tpl) => tpl.key === key);
}

/**
 * 按主体取全部模板（UI 做「全部场景」浏览时用；AI 选材请用 pickTemplates）。
 * @param {'manufacturer'|'clinic'|'doctor'|'platform'} subject
 * @returns {ActivityTemplate[]}
 */
export function getTemplatesBySubject(subject) {
  if (!subject) return [];
  return ACTIVITY_TEMPLATES.filter((tpl) => tpl.subject === subject);
}
