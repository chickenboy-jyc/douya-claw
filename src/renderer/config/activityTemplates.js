/** 预算级别对应的典型规模，用于 pickTemplates 的规模匹配打分 */
const SCALE_BY_BUDGET = { low: 'small', mid: 'medium', high: 'large' };

/** pickTemplates 各维度分值 */
const SCORE_WEIGHT = { goal: 10, form: 6, budget: 3, scale: 2 };

/**
 * 按主体 + 目标 + 形式 + 预算 推荐候选场景模板。
 *
 * 打分规则（subject 不精确匹配直接排除）：
 *   goals 含 goalKey(+10) > forms 含 form(+6) > budgetLevel 匹配(+3) > scale 与预算匹配(+2)
 *
 * 保证不返回空：即使所有加分项都不中，也会按主体返回前 limit 个模板。
 *
 * @param {Object} params
 * @param {'manufacturer'|'clinic'|'doctor'|'platform'} params.subject 主体（必填，不匹配返回空数组）
 * @param {string} [params.goalKey] 目标 key（ActivityGoal.key）
 * @param {'offline'|'online'|'hybrid'} [params.form] 活动形式
 * @param {'low'|'mid'|'high'} [params.budgetLevel] 预算级别
 * @param {number} [params.limit=3] 返回条数
 * @returns {ActivityTemplate[]} 按匹配度降序的模板数组
 */
export function pickTemplates({ subject, goalKey = '', form = '', budgetLevel = '', limit = 3 } = {}) {
  if (!subject) return [];

  const scored = ACTIVITY_TEMPLATES
    .filter((tpl) => tpl.subject === subject)
    .map((tpl, index) => {
      let score = 0;
      if (goalKey && tpl.goals.includes(goalKey)) score += SCORE_WEIGHT.goal;
      if (form && tpl.forms.includes(form)) score += SCORE_WEIGHT.form;
      if (budgetLevel && tpl.budgetLevel === budgetLevel) score += SCORE_WEIGHT.budget;
      if (budgetLevel && tpl.scale === SCALE_BY_BUDGET[budgetLevel]) score += SCORE_WEIGHT.scale;
      return { tpl, score, index };
    })
    .sort((a, b) => (b.score - a.score) || (a.index - b.index));

  return scored.slice(0, limit).map((item) => item.tpl);
}

