/**
 * 从登录名里取出「可以叫出口的名字」。
 *
 * 老板 2026-10-19：「登录的名字就是豆芽对用户的称呼」。
 * 所以这里**不做花哨清洗**（不猜姓、不截断、不转拼音），只做两件必要的事：
 *   ① 去掉邮箱域名（`zhangsan@x.com` → `zhangsan`），否则会念出整个邮箱；
 *   ② 空值/纯空白返回空串，调用方据此**不注入**称呼消息（不能注入一个空名字）。
 *
 * 为什么不做「像账号就返回空」的判断：那是**语义判断**，代码做不准。
 * （`lisi` 可能是真名拼音，也可能是账号名。）交给模型按 persona 的称呼规则自己判断，
 * 代码只负责把原始名字干净地递到它面前。
 *
 * @param {*} username 登录名（payload.username）
 * @returns {string} 可用的称呼候选；取不到时返回 ''
 */
function resolveCallName(username) {
  const raw = String(username == null ? '' : username).trim();
  if (!raw) return '';
  const at = raw.indexOf('@');
  const name = (at > 0 ? raw.slice(0, at) : raw).trim();
  return name;
}

/**
 * 构造「用户称呼」这条 system 消息。
 *
 * ⚠️ 返回空串时调用方必须**跳过注入** —— 往里塞一条「用户的名字是空」，比不注入更糟。
 *
 * @param {*} username 登录名（payload.username）
 * @returns {string} 可直接作为 system content 的文本；无可用名字时 ''
 */
function buildCallNamePrompt(username) {
  const name = resolveCallName(username);
  if (!name) return '';
  return [
    '【这位用户是谁】',
    '他的登录名是「' + name + '」。',
    '按人设里「怎么称呼用户」那一节决定怎么叫他 —— 名字像真名就用名字，像账号/手机号就直接用「你」，不要念出来。',
  ].join('\n');
}

module.exports = { DOUYA_PERSONA_PROMPT };

